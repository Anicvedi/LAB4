`timescale 1ns/1ps

module tb_booth_radix4_pipelined_multiplier;

/////////////////////////////////////////////////////
// Signals
/////////////////////////////////////////////////////
reg clk;
reg rst;
reg signed [7:0] A, B;
wire signed [15:0] product;

/////////////////////////////////////////////////////
// DUT
/////////////////////////////////////////////////////
booth_radix4_pipelined_multiplier uut (
    .clk(clk),
    .rst(rst),
    .multiplicand(A),
    .multiplier(B),
    .product(product)
);

/////////////////////////////////////////////////////
// Clock (100 MHz)
/////////////////////////////////////////////////////
always #5 clk = ~clk;

/////////////////////////////////////////////////////
// Stimulus
/////////////////////////////////////////////////////
initial begin
    clk = 0;
    rst = 1;
    A = 0;
    B = 0;

    // Reset
    #20;
    rst = 0;

    /////////////////////////////////////////////////////
    // Test 1
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = 10; B = 3;

    /////////////////////////////////////////////////////
    // Test 2
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = -5; B = 7;

    /////////////////////////////////////////////////////
    // Test 3
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = -8; B = -4;

    /////////////////////////////////////////////////////
    // Test 4
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = 15; B = -3;

    /////////////////////////////////////////////////////
    // Test 5
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = 0; B = 25;

    /////////////////////////////////////////////////////
    // Test 6 (edge)
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = 127; B = 1;

    /////////////////////////////////////////////////////
    // Test 7 (edge)
    /////////////////////////////////////////////////////
    @(posedge clk);
    A = -128; B = 1;

    /////////////////////////////////////////////////////
    // Let pipeline flush
    /////////////////////////////////////////////////////
    repeat(10) @(posedge clk);

    $finish;
end

endmodule
